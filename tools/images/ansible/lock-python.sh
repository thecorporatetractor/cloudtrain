#!/usr/bin/env bash
# Resolve requirements.in into requirements.lock (exact version + sha256 per wheel) inside
# the control node's base image, so the lock matches its Python (3.12) and platform.
# Wheels only (--only-binary), so the image build never compiles anything.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
base=$(sed -n 's/^FROM \(ubuntu:[^ ]*\).*/\1/p' "$here/Dockerfile" | head -1)
[[ -n $base ]] || { echo "no ubuntu FROM line in $here/Dockerfile" >&2; exit 1; }
out=$(mktemp -d); trap 'rm -rf "$out"' EXIT
docker run --rm -v "$here/requirements.in:/in/requirements.in:ro" -v "$out:/out" "$base" bash -ec '
  apt-get -qq update >/dev/null; apt-get -qq install -y --no-install-recommends python3-venv >/dev/null 2>&1
  python3 -m venv /v
  /v/bin/pip -q download --only-binary=:all: -d /out/dl -r /in/requirements.in
  chmod -R a+rwX /out'
{
  echo "# Generated by lock-python.sh from requirements.in; do not edit by hand."
  for w in "$out"/dl/*.whl; do
    f=$(basename "$w"); name=${f%%-*}; rest=${f#*-}; ver=${rest%%-*}
    name=$(tr '_' '-' <<<"$name" | tr '[:upper:]' '[:lower:]')
    printf '%s==%s --hash=sha256:%s\n' "$name" "$ver" "$(sha256sum "$w" | cut -d' ' -f1)"
  done | sort
} > "$here/requirements.lock"
echo "wrote $here/requirements.lock ($(grep -vc '^#' "$here/requirements.lock") packages)"
