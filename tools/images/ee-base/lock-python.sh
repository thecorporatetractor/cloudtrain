#!/usr/bin/env bash
# Resolve requirements.in into requirements.lock (exact version + sha256 per wheel) inside the
# AlmaLinux base image, so the lock matches its Python and platform. Wheels only.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
source "$here/../../../deploy/versions.env"
out=$(mktemp -d); trap 'rm -rf "$out"' EXIT
docker run --rm -v "$here/requirements.in:/in/requirements.in:ro" -v "$out:/out" "$ALMA_BASE_IMAGE" bash -ec '
  python3 -m venv /v 2>/dev/null || { dnf -y -q install python3 python3-pip >/dev/null; python3 -m venv /v; }
  /v/bin/pip -q download --only-binary=:all: -d /out/dl -r /in/requirements.in
  chmod -R a+rwX /out'
{
  echo "# Generated by lock-python.sh from requirements.in; do not edit by hand."
  for w in "$out"/dl/*.whl; do
    f=$(basename "$w"); name=${f%%-*}; rest=${f#*-}; ver=${rest%%-*}
    name=$(tr '_' '-' <<<"$name" | tr '[:upper:]' '[:lower:]')
    printf '%s==%s --hash=sha256:%s\n' "$name" "$ver" "$(sha256sum "$w" | cut -d' ' -f1)"
  done | sort
} > "$here/requirements.lock"
echo "wrote $here/requirements.lock ($(grep -vc '^#' "$here/requirements.lock") packages)"
