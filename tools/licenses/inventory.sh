#!/bin/bash
# Regenerates THIRD_PARTY_LICENSES.md from the production dependency trees
# (pnpm workspace + Go modules). Needs go-licenses (go install github.com/google/go-licenses/v2@latest).
set -euo pipefail
root=$(cd "$(dirname "$0")/../.." && pwd)
cd "$root"
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
pnpm licenses list --prod --json > "$tmp/js.json"
(cd services/lab-orchestrator && go-licenses report ./... 2>/dev/null) | grep -v '^github.com/cloudtrain/' > "$tmp/go.csv"
python3 - "$tmp/js.json" "$tmp/go.csv" > THIRD_PARTY_LICENSES.md <<'PY'
import csv, json, sys
js = json.load(open(sys.argv[1]))
print("# Third-party licenses\n")
print("Generated by `tools/licenses/inventory.sh`. Production dependencies only. Lab VM and")
print("container images (tools/images) contain further third-party software under its own")
print("licenses, e.g. Ubuntu, Kubernetes, containerd, Calico, etcd and FRRouting (GPL-2.0-or-later),")
print("distributed as separate images and not linked into CloudTrain. The IaC workstation image")
print("(tools/images/iac) ships Terraform under BUSL-1.1 (source-available, not open source; see the")
print("iac licensingNote in content/curriculum.yaml) unless built with IAC_CLI=tofu. The Ansible control")
print("node image (tools/images/ansible) ships ansible-core and its tools under GPL-3.0-or-later as")
print("separate programs with their licence texts; CloudTrain code does not import or link them. It")
print("also ships ansible-rulebook and drools_jpy (Apache-2.0) with OpenJDK 17 from the Ubuntu archive")
print("(GPL-2.0 with the Classpath Exception) and psycopg (LGPL-3.0), as separate programs. The Docker")
print("host VM image (docker-vm:29) ships cosign, notation and Trivy (Apache-2.0) as unmodified release")
print("binaries, the BuildKit and buildkit-syft-scanner images (Apache-2.0) and an offline Trivy")
print("vulnerability DB (public advisory data, under each source's terms).\n")
print("## JavaScript / TypeScript (pnpm workspace)\n")
print("| Package | Version | License |\n|---|---|---|")
rows = sorted((p["name"], ", ".join(p.get("versions", [])), lic) for lic, pkgs in js.items() for p in pkgs)
for name, ver, lic in rows:
    print(f"| {name} | {ver} | {lic} |")
print("\n## Go (services/lab-orchestrator)\n")
print("| Module | License |\n|---|---|")
for row in sorted(csv.reader(open(sys.argv[2]))):
    if row:
        print(f"| {row[0]} | {row[2]} |")
PY
echo "wrote THIRD_PARTY_LICENSES.md"
